// Package contractbundle merges the shared API contract
// (contracts/openapi.base.yaml) and one contract file per module
// (contracts/modules/*.yaml) into contracts/openapi.yaml, the single file that
// every code generator reads.
//
// Merging is where module isolation is enforced. Bundling fails if:
//   - two modules define the same path, component, permission, error code or job kind;
//   - a module defines a permission outside its own name (notes may only define notes:*);
//   - an operation has no operationId or no x-permission, or uses an unknown permission;
//   - a permission grants a role that does not exist, or a job names a missing payload schema;
//   - the merged result is not a valid OpenAPI document.
//
// All problems are reported together, so one run shows everything to fix.
package contractbundle

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
	"gopkg.in/yaml.v3"
)

// Header is written at the top of the generated file.
const Header = "GENERATED by `task gen` from contracts/openapi.base.yaml and contracts/modules/*.yaml.\n" +
	"DO NOT EDIT: change those files instead, then run `task gen`."

var (
	moduleNameRe = regexp.MustCompile(`^[a-z][a-z0-9_]*$`)
	permissionRe = regexp.MustCompile(`^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)*:[a-z][a-z_]*$`)
	errorCodeRe  = regexp.MustCompile(`^[A-Z][A-Z0-9_]*$`)
	jobKindRe    = regexp.MustCompile(`^[a-z][a-z0-9_]*\.[a-z][a-z0-9_]*$`)
	httpMethods  = []string{"get", "put", "post", "delete", "options", "head", "patch", "trace"}
	queues       = []string{"core", "ai"}
	priorities   = []string{"high", "normal", "low"}
	// Permission values every operation may use without a module declaring them.
	builtinPermissions = []string{"authenticated", "public"}
)

// The generated enums. The base file declares them with a placeholder value.
const (
	enumRole       = "Role"
	enumPermission = "Permission"
	enumErrorCode  = "ErrorCode"
	enumJobKind    = "JobKind"
)

type permissionMeta struct {
	Description string   `yaml:"description"`
	Sensitive   bool     `yaml:"sensitive"`
	Roles       []string `yaml:"roles"`
}

type errorCodeMeta struct {
	Status      int    `yaml:"status"`
	Description string `yaml:"description"`
}

type jobMeta struct {
	Queue   string `yaml:"queue"`
	Payload string `yaml:"payload"`
	// Priority: "high" (someone is waiting on screen), "normal" (the
	// default) or "low" (background upkeep). Workers take higher first.
	Priority    string `yaml:"priority"`
	Description string `yaml:"description"`
}

type moduleMeta struct {
	Name        string                    `yaml:"name"`
	Description string                    `yaml:"description"`
	Permissions map[string]permissionMeta `yaml:"permissions"`
	ErrorCodes  map[string]errorCodeMeta  `yaml:"errorCodes"`
	Jobs        map[string]jobMeta        `yaml:"jobs"`
}

type owned[T any] struct {
	module string // "" for the shared base file
	meta   T
}

type operationRef struct {
	file, method, path, permission string
}

type bundler struct {
	root        *yaml.Node // mapping node of the output document
	problems    []string
	pathOwner   map[string]string
	compOwner   map[string]string // "schemas/Candidate" -> module
	permissions map[string]owned[permissionMeta]
	errorCodes  map[string]owned[errorCodeMeta]
	jobs        map[string]owned[jobMeta]
	roles       []string
	modules     []moduleMeta
	operations  []operationRef
	operationID map[string]string // operationId -> file
}

// BundleFiles reads the base file and every *.yaml in modulesDir (in name
// order) and returns the merged, validated contract.
func BundleFiles(basePath, modulesDir string) ([]byte, error) {
	base, err := readYAML(basePath)
	if err != nil {
		return nil, err
	}
	files, err := filepath.Glob(filepath.Join(modulesDir, "*.yaml"))
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	mods := make([]namedDoc, 0, len(files))
	for _, f := range files {
		doc, err := readYAML(f)
		if err != nil {
			return nil, err
		}
		mods = append(mods, namedDoc{name: f, doc: doc})
	}
	return Bundle(namedDoc{name: basePath, doc: base}, mods)
}

type namedDoc struct {
	name string
	doc  *yaml.Node
}

// Bundle merges already-parsed documents. Exposed for tests.
func Bundle(base namedDoc, modules []namedDoc) ([]byte, error) {
	b := &bundler{
		pathOwner:   map[string]string{},
		compOwner:   map[string]string{},
		permissions: map[string]owned[permissionMeta]{},
		errorCodes:  map[string]owned[errorCodeMeta]{},
		jobs:        map[string]owned[jobMeta]{},
		operationID: map[string]string{},
	}
	if err := b.loadBase(base); err != nil {
		return nil, err
	}
	for _, m := range modules {
		b.addModule(m)
	}
	b.checkReferences()
	if len(b.problems) > 0 {
		return nil, fmt.Errorf("the API contract has %d problem(s):\n  - %s", len(b.problems), strings.Join(b.problems, "\n  - "))
	}
	b.writeGenerated()

	stripComments(b.root)
	b.root.HeadComment = Header
	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(b.root); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	if err := validateOpenAPI(buf.Bytes()); err != nil {
		return nil, fmt.Errorf("the merged contract is not valid OpenAPI: %w", err)
	}
	return buf.Bytes(), nil
}

func (b *bundler) problem(format string, args ...any) {
	b.problems = append(b.problems, fmt.Sprintf(format, args...))
}

func (b *bundler) loadBase(base namedDoc) error {
	root := documentRoot(base.doc)
	if root == nil {
		return fmt.Errorf("%s: expected a YAML mapping at the top level", base.name)
	}
	b.root = root
	ensureMapping(root, "paths")
	components := ensureMapping(root, "components")
	ensureMapping(components, "schemas")

	rolesNode := mapGet(root, "x-roles")
	if rolesNode == nil || rolesNode.Kind != yaml.MappingNode {
		return fmt.Errorf("%s: x-roles must be a mapping of role name to description", base.name)
	}
	for i := 0; i < len(rolesNode.Content); i += 2 {
		b.roles = append(b.roles, rolesNode.Content[i].Value)
	}

	var codes map[string]errorCodeMeta
	if n := mapGet(root, "x-error-codes"); n != nil {
		if err := n.Decode(&codes); err != nil {
			return fmt.Errorf("%s: x-error-codes: %w", base.name, err)
		}
	}
	for code, meta := range codes {
		b.addErrorCode(base.name, "", code, meta)
	}
	for _, name := range []string{enumRole, enumPermission, enumErrorCode, enumJobKind} {
		if mapGet(mapGet(components, "schemas"), name) == nil {
			return fmt.Errorf("%s: components.schemas.%s placeholder is missing", base.name, name)
		}
	}
	for path := range mappingEntries(mapGet(root, "paths")) {
		b.problem("%s: path %q must live in a module file, not the base file", base.name, path)
	}
	return nil
}

func (b *bundler) addModule(m namedDoc) {
	file := m.name
	root := documentRoot(m.doc)
	if root == nil {
		b.problem("%s: expected a YAML mapping at the top level", file)
		return
	}
	for key := range mappingEntries(root) {
		if key != "x-module" && key != "paths" && key != "components" {
			b.problem("%s: unexpected top-level key %q (allowed: x-module, paths, components)", file, key)
		}
	}

	var meta moduleMeta
	metaNode := mapGet(root, "x-module")
	if metaNode == nil {
		b.problem("%s: missing x-module block", file)
		return
	}
	if err := metaNode.Decode(&meta); err != nil {
		b.problem("%s: x-module: %v", file, err)
		return
	}
	wantName := strings.TrimSuffix(filepath.Base(file), filepath.Ext(file))
	if meta.Name != wantName {
		b.problem("%s: x-module.name is %q but must match the file name %q", file, meta.Name, wantName)
	}
	if !moduleNameRe.MatchString(meta.Name) {
		b.problem("%s: module name %q must be lower_snake_case", file, meta.Name)
	}
	if strings.TrimSpace(meta.Description) == "" {
		b.problem("%s: x-module.description is required", file)
	}
	b.modules = append(b.modules, meta)

	for name, p := range meta.Permissions {
		b.addPermission(file, meta.Name, name, p)
	}
	for code, e := range meta.ErrorCodes {
		b.addErrorCode(file, meta.Name, code, e)
	}
	for kind, j := range meta.Jobs {
		b.addJob(file, meta.Name, kind, j)
	}

	paths := mapGet(b.root, "paths")
	for path, item := range mappingEntries(mapGet(root, "paths")) {
		if owner, ok := b.pathOwner[path]; ok {
			b.problem("%s: path %q is already defined by module %q", file, path, owner)
			continue
		}
		b.pathOwner[path] = meta.Name
		b.checkOperations(file, path, item)
		mapAppend(paths, path, item)
	}

	components := mapGet(b.root, "components")
	for section, entries := range mappingEntries(mapGet(root, "components")) {
		target := ensureMapping(components, section)
		for name, value := range mappingEntries(entries) {
			key := section + "/" + name
			if owner, ok := b.compOwner[key]; ok {
				b.problem("%s: components.%s.%s is already defined by module %q", file, section, name, owner)
				continue
			}
			if mapGet(target, name) != nil {
				b.problem("%s: components.%s.%s is already defined in the base file", file, section, name)
				continue
			}
			b.compOwner[key] = meta.Name
			mapAppend(target, name, value)
		}
	}
}

func (b *bundler) checkOperations(file, path string, item *yaml.Node) {
	for method, op := range mappingEntries(item) {
		if !slices.Contains(httpMethods, method) {
			continue
		}
		where := fmt.Sprintf("%s: %s %s", file, strings.ToUpper(method), path)
		opID := scalarAt(op, "operationId")
		if opID == "" {
			b.problem("%s: operationId is required", where)
		} else if other, ok := b.operationID[opID]; ok {
			b.problem("%s: operationId %q is already used in %s", where, opID, other)
		} else {
			b.operationID[opID] = file
		}
		perm := scalarAt(op, "x-permission")
		if perm == "" {
			b.problem("%s: x-permission is required (use `authenticated` for any signed-in user)", where)
			continue
		}
		b.operations = append(b.operations, operationRef{file: file, method: method, path: path, permission: perm})
	}
}

func (b *bundler) addPermission(file, module, name string, p permissionMeta) {
	if !permissionRe.MatchString(name) {
		b.problem("%s: permission %q must look like resource:action, e.g. %s:read", file, name, module)
		return
	}
	resource := name[:strings.IndexByte(name, ':')]
	if resource != module && !strings.HasPrefix(resource, module+".") {
		b.problem("%s: permission %q must start with the module name %q", file, name, module)
		return
	}
	if prev, ok := b.permissions[name]; ok {
		b.problem("%s: permission %q is already defined by module %q", file, name, prev.module)
		return
	}
	if strings.TrimSpace(p.Description) == "" {
		b.problem("%s: permission %q needs a description", file, name)
	}
	for _, r := range p.Roles {
		if !slices.Contains(b.roles, r) {
			b.problem("%s: permission %q grants unknown role %q (roles are declared in x-roles)", file, name, r)
		}
	}
	b.permissions[name] = owned[permissionMeta]{module: module, meta: p}
}

func (b *bundler) addErrorCode(file, module, code string, e errorCodeMeta) {
	if !errorCodeRe.MatchString(code) {
		b.problem("%s: error code %q must be UPPER_SNAKE_CASE", file, code)
		return
	}
	if prev, ok := b.errorCodes[code]; ok {
		owner := prev.module
		if owner == "" {
			owner = "the base file"
		} else {
			owner = "module " + owner
		}
		b.problem("%s: error code %q is already defined by %s", file, code, owner)
		return
	}
	if e.Status < 400 || e.Status > 599 {
		b.problem("%s: error code %q needs an HTTP status between 400 and 599", file, code)
	}
	if strings.TrimSpace(e.Description) == "" {
		b.problem("%s: error code %q needs a description", file, code)
	}
	b.errorCodes[code] = owned[errorCodeMeta]{module: module, meta: e}
}

func (b *bundler) addJob(file, module, kind string, j jobMeta) {
	if !jobKindRe.MatchString(kind) {
		b.problem("%s: job kind %q must look like entity.action, e.g. document.extract_text", file, kind)
		return
	}
	if prev, ok := b.jobs[kind]; ok {
		b.problem("%s: job kind %q is already defined by module %q", file, kind, prev.module)
		return
	}
	if !slices.Contains(queues, j.Queue) {
		b.problem("%s: job %q has queue %q; use one of %v", file, kind, j.Queue, queues)
	}
	if j.Payload == "" {
		b.problem("%s: job %q needs a payload schema name", file, kind)
	}
	if j.Priority == "" {
		j.Priority = "normal"
	}
	if !slices.Contains(priorities, j.Priority) {
		b.problem("%s: job %q has priority %q; use one of %v", file, kind, j.Priority, priorities)
	}
	b.jobs[kind] = owned[jobMeta]{module: module, meta: j}
}

// checkReferences runs once everything is merged.
func (b *bundler) checkReferences() {
	for _, op := range b.operations {
		if slices.Contains(builtinPermissions, op.permission) {
			continue
		}
		if _, ok := b.permissions[op.permission]; !ok {
			b.problem("%s: %s %s uses x-permission %q, which no module declares", op.file, strings.ToUpper(op.method), op.path, op.permission)
		}
	}
	schemas := mapGet(mapGet(b.root, "components"), "schemas")
	for kind, j := range b.jobs {
		if j.meta.Payload != "" && mapGet(schemas, j.meta.Payload) == nil {
			b.problem("module %q: job %q names payload schema %q, which does not exist", j.module, kind, j.meta.Payload)
		}
	}
}

// writeGenerated fills the generated enums and the x-* summary blocks.
func (b *bundler) writeGenerated() {
	schemas := mapGet(mapGet(b.root, "components"), "schemas")
	setEnum(mapGet(schemas, enumRole), b.roles)
	setEnum(mapGet(schemas, enumPermission), sortedKeys(b.permissions))
	setEnum(mapGet(schemas, enumErrorCode), sortedKeys(b.errorCodes))
	setEnum(mapGet(schemas, enumJobKind), sortedKeys(b.jobs))

	perms := &yaml.Node{Kind: yaml.MappingNode}
	for _, name := range sortedKeys(b.permissions) {
		p := b.permissions[name]
		mapAppend(perms, name, encodeNode(struct {
			Module      string   `yaml:"module"`
			Description string   `yaml:"description"`
			Sensitive   bool     `yaml:"sensitive"`
			Roles       []string `yaml:"roles,flow"`
		}{p.module, p.meta.Description, p.meta.Sensitive, p.meta.Roles}))
	}
	mapSet(b.root, "x-permissions", perms)

	codes := &yaml.Node{Kind: yaml.MappingNode}
	for _, code := range sortedKeys(b.errorCodes) {
		e := b.errorCodes[code]
		module := e.module
		if module == "" {
			module = "shared"
		}
		mapAppend(codes, code, encodeNode(struct {
			Module      string `yaml:"module"`
			Status      int    `yaml:"status"`
			Description string `yaml:"description"`
		}{module, e.meta.Status, e.meta.Description}))
	}
	mapSet(b.root, "x-error-codes", codes)

	jobs := &yaml.Node{Kind: yaml.MappingNode}
	for _, kind := range sortedKeys(b.jobs) {
		j := b.jobs[kind]
		mapAppend(jobs, kind, encodeNode(struct {
			Module      string `yaml:"module"`
			Queue       string `yaml:"queue"`
			Payload     string `yaml:"payload"`
			Priority    string `yaml:"priority"`
			Description string `yaml:"description"`
		}{j.module, j.meta.Queue, j.meta.Payload, j.meta.Priority, j.meta.Description}))
	}
	mapSet(b.root, "x-jobs", jobs)

	mods := &yaml.Node{Kind: yaml.SequenceNode}
	for _, m := range b.modules {
		mods.Content = append(mods.Content, encodeNode(struct {
			Name        string `yaml:"name"`
			Description string `yaml:"description"`
		}{m.Name, strings.TrimSpace(m.Description)}))
	}
	mapSet(b.root, "x-modules", mods)
}

func validateOpenAPI(data []byte) error {
	loader := openapi3.NewLoader()
	doc, err := loader.LoadFromData(data)
	if err != nil {
		return err
	}
	return doc.Validate(context.Background(), openapi3.EnableExamplesValidation())
}

